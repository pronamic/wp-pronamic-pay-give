namespace Pronamic\WordPress\Pay\Extensions\Give\Gateways;

use Pronamic\WordPress\Pay\Core\PaymentMethods;
use Pronamic\WordPress\Pay\Extensions\Give\Gateway;

/**
 * %1$s gateway class
 */
final class %2$sGateway extends Gateway {
	/**
	 * Gateway ID.
	 *
	 * @return string
	 */
	public static function id(): string {
		return '%3$s';
	}

	/**
	 * Payment method.
	 *
	 * @return string
	 */
	public function get_payment_method(): string {
		return PaymentMethods::%4$s;
	}
}

PHP;

$gateways_dir = __DIR__ . '/../src/Gateways';

if ( ! is_dir( $gateways_dir ) ) {
	mkdir( $gateways_dir, 0755, true );
}

$map_lines = [];

$key_width = 0;

foreach ( $methods as $method ) {
	$key_width = max( $key_width, strlen( 'PaymentMethods::' . $method[0] ) );
}

foreach ( $methods as $method ) {
	list( $constant, $class_base, $id ) = $method;

	$class_name = $class_base . 'Gateway';

	$contents = sprintf( $header, $class_base, $class_base, $id, $constant );

	file_put_contents( $gateways_dir . '/' . $class_name . '.php', $contents );

	$key = 'PaymentMethods::' . $constant;

	$map_lines[] = sprintf(
		"\t\t\t%s => Gateways\\%s::class,",
		str_pad( $key, $key_width ),
		$class_name
	);
}

$repository = <<<PHP
<?php
/**
 * Gateway repository.
 *
 * Generated by `bin/generate-give-gateways.php` — do not edit manually.
 *
 * @author    Pronamic <info@pronamic.eu>
 * @copyright 2005-2026 Pronamic
 * @license   GPL-2.0-or-later
 * @package   Pronamic\WordPress\Pay\Extensions\Give
 */

namespace Pronamic\WordPress\Pay\Extensions\Give;

use Pronamic\WordPress\Pay\Core\PaymentMethods;

/**
 * Gateway repository class
 */
final class GatewayRepository {
	/**
	 * Map of Pronamic payment method to Give gateway class.
	 *
	 * @return array<string, class-string<Gateway>>
	 */
	public static function get_map(): array {
		return [
%s
		];
	}
}

PHP;

file_put_contents(
	__DIR__ . '/../src/GatewayRepository.php',
	sprintf( $repository, implode( "\n", $map_lines ) )
);

echo 'Generated ' . count( $methods ) . " gateway classes and the gateway repository.\n";
